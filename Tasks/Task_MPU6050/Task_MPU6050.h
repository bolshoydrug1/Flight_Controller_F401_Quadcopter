#ifndef TASK_mpu6050_TASK_mpu6050_H_
#define TASK_mpu6050_TASK_mpu6050_H_

#include <stdbool.h>
#include <stdint.h>
#include "FreeRTOS.h"
#include "task.h"
#include "MPU6050.h"

// Конфигурация задачи (можно менять под свои нужды)
#define TASK_mpu6050_STACK_SIZE    (configMINIMAL_STACK_SIZE * 2)
// Выше остальных периодических задач (все на tskIDLE_PRIORITY + 4): при
// равном приоритете и вытесняющем планировщике готовая к работе задача
// телеметрии/эхолота/etc. может отобрать квант времени ровно в момент, когда
// нужно уложиться в фазу 1кГц цикла IMU. Приоритет здесь гарантирует, что
// цикл MPU6050 всегда вытесняет остальные, а не ждёт round-robin.
#define TASK_mpu6050_PRIORITY      (tskIDLE_PRIORITY + 6)
#define TASK_mpu6050_NAME          "Task_mpu6050"

/**
 * @brief Запускает задачу.
 * Если задача уже запущена, функция ничего не делает.
 *
 * При старте задача сама инициализирует MPU6050 (см. lora-style ретрай в
 * теле задачи) и калибрует гироскоп (результат только в ОЗУ, см.
 * MPU6050_CalibrateGyro) - датчик должен быть неподвижен в этот момент.
 * Дальше задача читает accel+gyro по DMA на 1кГц, не блокируя CPU на время
 * самого обмена по I2C.
 */
void Task_mpu6050_Start(void);

/**
 * @brief Останавливает (удаляет) задачу.
 */
void Task_mpu6050_Stop(void);

/**
 * @brief Проверяет статус задачи.
 * @return true, если задача запущена и выполняется.
 * @return false, если задача остановлена или удалена.
 */
bool Task_mpu6050_IsRunning(void);

/**
 * @brief Потокобезопасно возвращает последние прочитанные и
 *        скомпенсированные (offset + масштаб) данные IMU.
 * @param out Куда скопировать данные.
 * @retval true, если данные скопированы; false, если задача ещё не сделала
 *         ни одного успешного чтения или мьютекс занят дольше таймаута.
 */
bool Task_mpu6050_GetData(MPU6050_ScaledData *out);

/**
 * @brief Запрашивает калибровку нуля акселерометра по внешней команде
 *        (например, будущая команда с земли по LoRa - на данный момент
 *        такого типа пакета ещё нет в Telemetry_Data.h, вызов этой функции
 *        нужно подключить к обработчику команды отдельно).
 *
 *        Калибровка выполняется внутри цикла задачи (между итерациями 1кГц
 *        чтения) и включает блокирующее усреднение `samples` отсчётов и
 *        запись во flash (MPU6050_SaveAccelOffsetToFlash) - на время erase
 *        сектора выполнение кода на MCU полностью останавливается на
 *        аппаратном уровне. Вызывать только на земле, когда дрон неподвижен
 *        и лежит строго горизонтально осью Z вверх - см. MPU6050_CalibrateAccel.
 * @param samples Число отсчётов для усреднения (типично 1000-2000), 0 недопустим.
 * @retval true, если запрос принят (задача ещё не запущена/задача не готова
 *         принять запрос - маловероятно, но проверяется).
 */
bool Task_mpu6050_RequestAccelCalibration(uint16_t samples);

/**
 * @brief true, если калибровка акселерометра сейчас выполняется (1кГц чтение
 *        приостановлено на это время).
 */
bool Task_mpu6050_IsCalibratingAccel(void);

#endif /* TASK_mpu6050_TASK_mpu6050_H_ */
